package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"sort"
	"strconv"
)

// Generator for keysyms_generated.go
// Usage: go generate ./...

func main() {
	file, err := os.Open("/usr/include/X11/keysymdef.h")
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error: %v\n", err)
		fmt.Fprintf(os.Stderr, "Install X11 headers: sudo apt install libx11-dev\n")
		os.Exit(1)
	}

	// Match lines like: #define XK_A 0x0041 /* U+0041 LATIN CAPITAL LETTER A */
	re := regexp.MustCompile(`#define\s+XK_(\w+)\s+0x[0-9a-fA-F]+\s*/\*\s*U\+([0-9A-Fa-f]{4,6})`)

	keysyms := make(map[string]rune)
	scanner := bufio.NewScanner(file)
	for scanner.Scan() {
		if m := re.FindStringSubmatch(scanner.Text()); m != nil {
			if cp, err := strconv.ParseInt(m[2], 16, 32); err == nil {
				keysyms[m[1]] = rune(cp)
			}
		}
	}

	// Sort keys for stable output
	keys := make([]string, 0, len(keysyms))
	for k := range keysyms {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	// Close input file before creating output
	file.Close()

	// Write to file
	out, err := os.Create("keysyms_generated.go")
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error creating output file: %v\n", err)
		os.Exit(1)
	}
	defer out.Close()

	fmt.Fprintln(out, "// Code generated by go generate. DO NOT EDIT.")
	fmt.Fprintln(out, "")
	fmt.Fprintln(out, "package runtime")
	fmt.Fprintln(out, "")
	fmt.Fprintf(out, "// keysymMap contains %d X11 keysym to Unicode mappings\n", len(keysyms))
	fmt.Fprintln(out, "var keysymMap = map[string]rune{")
	for _, k := range keys {
		fmt.Fprintf(out, "\t%q: 0x%04X,\n", k, keysyms[k])
	}
	fmt.Fprintln(out, "}")

	fmt.Printf("Generated keysyms_generated.go (%d mappings)\n", len(keysyms))
}
